#!/usr/bin/env node
// Writes src/05-book-text.js from the author's manuscript, word for word.
//
//   node tools/book-text.cjs --docx-dir <folder with the unzipped "El lado oscuro del mono.docx">
//
// (Unzip the .docx first: it is a zip file; on Windows, copy it as .zip and use "Extract all".)
// The manuscript stays out of the repository; only the generated texts are published with the page.
// Paragraphs are copied as they are — spelling, spacing and punctuation included. Empty paragraphs inside a text are
// kept as pauses; the "(QR → …)" lines of the print edition become `qr` (the web plays the song itself).
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const args = process.argv.slice(2);
const i = args.indexOf('--docx-dir');
if (i < 0 || !args[i + 1]) { console.error('usage: node tools/book-text.cjs --docx-dir <unzipped docx folder>'); process.exit(1); }
const xml = fs.readFileSync(path.join(args[i + 1], 'word', 'document.xml'), 'utf8');

const unescape = (s) => s.replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&');
const paras = [...xml.matchAll(/<w:p[ >][\s\S]*?<\/w:p>/g)].map(([p]) => {
  const style = (/<w:pStyle w:val="([^"]+)"/.exec(p) || [])[1] || '';
  const runs = [...p.matchAll(/<w:r[ >][\s\S]*?<\/w:r>/g)].map(([r]) => ({
    t: [...r.matchAll(/<w:t(?: [^>]*)?>([^<]*)<\/w:t>|<w:(tab|br)\/>/g)].map((m) => (m[2] === 'tab' ? '\t' : m[2] === 'br' ? '\n' : unescape(m[1]))).join(''),
    b: /<w:b\/>|<w:b w:val="(1|true)"\/>/.test(r),
  })).filter((r) => r.t);
  const t = runs.map((r) => r.t).join('');
  return { style, t, bold: runs.length > 0 && runs.every((r) => r.b) };
});

// where each text starts and ends in the manuscript (checked below: anything unexpected stops the script)
const at = (re, from = 0) => { const n = paras.findIndex((p, k) => k >= from && re.test(p.t)); if (n < 0) { console.error('book-text: not found ' + re); process.exit(1); } return n; };
const H = {
  dedicatoria: at(/^Dedicatoria$/),
  contraportada: at(/^Contraportada$/),
  agradecimientos: at(/^Agradecimientos$/),
  prologo: at(/^\[Pensamientos intrusivos/),
};
for (let n = 1; n <= 9; n++) H['cap-' + n] = at(new RegExp('^Capítulo ' + n + ' — '));
H.cierre = at(/^No hay un sentido en esta vida\.$/, H['cap-9']);
const order = Object.entries(H).sort((a, b) => a[1] - b[1]);

const QR = /\s*\(QR → “([^”]+)”\)\s*$/;
const out = {};
order.forEach(([id, start], k) => {
  const end = k + 1 < order.length ? order[k + 1][1] : paras.length;
  const isText = id === 'cierre';
  let heading = isText ? '' : paras[start].t, qr = null, from = isText ? start : start + 1;
  const inl = QR.exec(heading);
  if (inl) { qr = inl[1]; heading = heading.slice(0, inl.index); }
  else if (from < end && QR.test(paras[from].t) && /^\(QR/.test(paras[from].t.trim())) { qr = QR.exec(paras[from].t)[1]; from++; }
  let body = paras.slice(from, end);
  while (body.length && !body[0].t.trim()) body.shift();
  while (body.length && !body[body.length - 1].t.trim()) body.pop();
  if (!body.length) { console.error('book-text: empty text ' + id); process.exit(1); }
  out[id] = { heading, ...(qr ? { qr } : {}), paras: body.map((p) => (p.bold ? { t: p.t, b: 1 } : p.t)) };
});

const js = [
  '// ═══════════════════════════════════════════════════════════════════════════════════════════',
  '// THE BOOK\'S TEXTS  (generated by tools/book-text.cjs from the author\'s manuscript — do not edit by hand)',
  '//   Each paragraph exactly as written; "" is a pause between paragraphs; { t, b: 1 } is a bold paragraph.',
  '// ═══════════════════════════════════════════════════════════════════════════════════════════',
  'const BOOK_TEXT = ' + JSON.stringify(out, null, 1).replace(/\n\s*/g, ' ').replace(/\{ "/g, '{ "').replace(/("paras": \[)/g, '$1') + ';',
  '',
].join('\n').replace(/\}, "/g, '},\n  "').replace(/^const BOOK_TEXT = \{ /m, 'const BOOK_TEXT = {\n  ').replace(/\} \};\n$/, '},\n};\n');
fs.writeFileSync(path.join(ROOT, 'src', '05-book-text.js'), js);
console.log('book-text → src/05-book-text.js: ' + order.map(([id]) => `${id} (${out[id].paras.length})`).join(', '));
